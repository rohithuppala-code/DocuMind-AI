import React, { useState } from 'react';
import { HelpCircle, CheckCircle2, XCircle, RotateCcw, Trophy, Award, ArrowRight } from 'lucide-react';
import { QuizQuestion } from '../types';

interface QuizArenaProps {
  quizQuestions: QuizQuestion[];
}

export const QuizArena: React.FC<QuizArenaProps> = ({ quizQuestions }) => {
  const [currentIdx, setCurrentIdx] = useState(0);
  const [selectedAnswers, setSelectedAnswers] = useState<Record<number, string>>({});
  const [showExplanation, setShowExplanation] = useState<Record<number, boolean>>({});
  const [isCompleted, setIsCompleted] = useState(false);

  if (!quizQuestions || quizQuestions.length === 0) {
    return (
      <div className="bg-slate-900 border border-slate-800 rounded-2xl p-12 text-center text-slate-400">
        <HelpCircle className="w-10 h-10 mx-auto mb-3 text-slate-600" />
        <p className="font-semibold text-sm">No quiz questions generated</p>
        <p className="text-xs text-slate-500 mt-1">Run the LangGraph workflow to synthesize an adaptive assessment quiz.</p>
      </div>
    );
  }

  const currentQ = quizQuestions[currentIdx];
  const selected = selectedAnswers[currentIdx];
  const isAnswered = selected !== undefined;
  const isCorrect = selected === currentQ.correct_answer;

  const handleSelectOption = (label: string) => {
    if (isAnswered) return; // Prevent changing after answer
    setSelectedAnswers(prev => ({ ...prev, [currentIdx]: label }));
    setShowExplanation(prev => ({ ...prev, [currentIdx]: true }));
  };

  const handleNext = () => {
    if (currentIdx < quizQuestions.length - 1) {
      setCurrentIdx(prev => prev + 1);
    } else {
      setIsCompleted(true);
    }
  };

  const handleRestart = () => {
    setSelectedAnswers({});
    setShowExplanation({});
    setCurrentIdx(0);
    setIsCompleted(false);
  };

  // Calculate final score
  const score = Object.entries(selectedAnswers).filter(
    ([idx, ans]) => ans === quizQuestions[Number(idx)].correct_answer
  ).length;

  if (isCompleted) {
    const percentage = Math.round((score / quizQuestions.length) * 100);

    return (
      <div className="max-w-xl mx-auto bg-slate-900 border border-slate-800 rounded-2xl p-8 text-center shadow-2xl space-y-6">
        <div className="w-16 h-16 rounded-2xl bg-gradient-to-tr from-amber-500 to-yellow-400 mx-auto flex items-center justify-center shadow-lg shadow-amber-500/20">
          <Trophy className="w-8 h-8 text-slate-950" />
        </div>

        <div>
          <h3 className="text-xl font-bold text-white">Assessment Completed!</h3>
          <p className="text-xs text-slate-400 mt-1">
            Grounded assessment generated by LangGraph Agent 5
          </p>
        </div>

        <div className="p-6 bg-slate-950 rounded-xl border border-slate-800">
          <div className="text-4xl font-extrabold text-transparent bg-clip-text bg-gradient-to-r from-indigo-400 to-emerald-400">
            {score} / {quizQuestions.length}
          </div>
          <p className="text-xs text-slate-400 mt-2 font-medium">
            Overall Accuracy: <strong className="text-white">{percentage}%</strong>
          </p>
        </div>

        <button
          onClick={handleRestart}
          className="flex items-center justify-center gap-2 w-full py-3 rounded-xl bg-indigo-600 hover:bg-indigo-500 font-semibold text-sm text-white transition-all shadow-lg shadow-indigo-500/20"
        >
          <RotateCcw className="w-4 h-4" />
          <span>Retake Assessment</span>
        </button>
      </div>
    );
  }

  return (
    <div className="max-w-2xl mx-auto space-y-6">
      {/* Quiz Progress Header */}
      <div className="flex items-center justify-between pb-3 border-b border-slate-800">
        <div>
          <h3 className="text-sm font-bold text-white flex items-center gap-2">
            <HelpCircle className="w-4 h-4 text-indigo-400" />
            Adaptive Practice Quiz
          </h3>
          <p className="text-xs text-slate-400">
            Question {currentIdx + 1} of {quizQuestions.length} • Concept: <strong className="text-indigo-300">{currentQ.concept_tested}</strong>
          </p>
        </div>

        <span className="text-xs px-2.5 py-1 rounded-full bg-slate-800 text-slate-300 font-semibold border border-slate-700">
          Score: {score}
        </span>
      </div>

      {/* Question Card */}
      <div className="bg-slate-900 border border-slate-800 rounded-2xl p-6 shadow-xl space-y-6">
        <h4 className="text-base font-bold text-white leading-snug">
          {currentQ.question}
        </h4>

        {/* 4 Multiple Choice Options */}
        <div className="space-y-3">
          {currentQ.options.map((opt) => {
            const isOptSelected = selected === opt.label;
            const isOptCorrect = opt.label === currentQ.correct_answer;

            let btnStyle = 'bg-slate-950 hover:bg-slate-800/80 border-slate-800 text-slate-200';
            if (isAnswered) {
              if (isOptCorrect) {
                btnStyle = 'bg-emerald-950/40 border-emerald-500/80 text-emerald-200 shadow-md shadow-emerald-500/10';
              } else if (isOptSelected) {
                btnStyle = 'bg-rose-950/40 border-rose-500/80 text-rose-200 shadow-md shadow-rose-500/10';
              } else {
                btnStyle = 'bg-slate-950 border-slate-800/60 text-slate-500 opacity-60';
              }
            }

            return (
              <button
                key={opt.label}
                onClick={() => handleSelectOption(opt.label)}
                disabled={isAnswered}
                className={`w-full text-left p-4 rounded-xl border transition-all flex items-start gap-3.5 ${btnStyle}`}
              >
                <span className={`w-6 h-6 rounded-lg flex items-center justify-center text-xs font-bold shrink-0 ${
                  isAnswered && isOptCorrect
                    ? 'bg-emerald-500 text-slate-950'
                    : isAnswered && isOptSelected
                    ? 'bg-rose-500 text-white'
                    : 'bg-slate-800 text-slate-300'
                }`}>
                  {opt.label}
                </span>
                <span className="text-xs sm:text-sm font-medium leading-relaxed pt-0.5">
                  {opt.text}
                </span>
              </button>
            );
          })}
        </div>

        {/* Explanation Card */}
        {isAnswered && (
          <div className={`p-4 rounded-xl border text-xs leading-relaxed space-y-1.5 transition-all ${
            isCorrect ? 'bg-emerald-950/20 border-emerald-500/30' : 'bg-amber-950/20 border-amber-500/30'
          }`}>
            <div className="flex items-center gap-2 font-bold">
              {isCorrect ? (
                <>
                  <CheckCircle2 className="w-4 h-4 text-emerald-400" />
                  <span className="text-emerald-300">Correct Answer!</span>
                </>
              ) : (
                <>
                  <XCircle className="w-4 h-4 text-rose-400" />
                  <span className="text-rose-300">Incorrect. Correct Answer: {currentQ.correct_answer}</span>
                </>
              )}
            </div>
            <p className="text-slate-300 pl-6">
              {currentQ.explanation}
            </p>
          </div>
        )}

        {/* Next Question Control */}
        {isAnswered && (
          <div className="flex justify-end pt-2">
            <button
              onClick={handleNext}
              className="flex items-center gap-2 px-5 py-2.5 rounded-xl bg-indigo-600 hover:bg-indigo-500 font-semibold text-xs text-white transition-all shadow-md shadow-indigo-500/20"
            >
              <span>{currentIdx < quizQuestions.length - 1 ? 'Next Question' : 'Complete Assessment'}</span>
              <ArrowRight className="w-4 h-4" />
            </button>
          </div>
        )}
      </div>
    </div>
  );
};

